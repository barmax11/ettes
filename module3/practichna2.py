# Завдання 6
# Користувач вводить суму кредиту та термін у роках.
# Виберіть відсоткову ставку за такими умовами:
# ● Для кредиту до 10 000$ на термін до 3 років – ставка
# 8%
# ● Для кредиту до 10 000$ на термін понад 3 роки –
# ставка 10%
# ● Для кредиту від 10 001$ до 50 000$ на термін до 3
# років – ставка 12%
# ● Для кредиту від 10 001$ до 50 000$ на термін понад 3
# роки – ставка 14%
# ● Для кредиту від 50 000$ на будь-який термін – ставка
# 20%
# Виведіть відсоткову ставку, загальну суму кредиту та
# щомісячний платіж
# Загальна сума кредиту вираховується так

credit = float(input("Введіть суму кередиту :"))
time = float(input("Введіть терму кредиту у роках :"))

if credit <= 10000 and time <= 3:
    percent = 8
elif credit < 10000 and time >= 3:
    percent = 10
elif 10000 < credit <= 50000 and time <= 3:
    percent = 12
elif 10000 < credit <= 50000 and time >= 3:
    percent = 14
else:
    percent = 20

total = credit * (1 + percent / 100) ** time
monthly_payment = total / (time * 12)

print(f"Відсоткова ставка: {percent}%")
print(f"Загальна сума кредиту: {total} доларів")
print(f"Щомісячний платіж: {monthly_payment} доларів ")
